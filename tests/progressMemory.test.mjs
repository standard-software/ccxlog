function progressBodyBytes(pairs) {
  return JSON.stringify(pairs.map(p => p.progressEntries.map(e => e.message?.content ?? null))).length;
}

test('P-4: discarded data omits tool I/O, reasoning text, and toolUseResult', async (t) => {
  const src = await fixturePairs(t);
  const heavy = ['output line 11', 'internal reasoning that only ProgressFull shows', '"limit":100'];
  for (const [source, pairs] of Object.entries(src)) {
    const dropped = structuredClone(pairs);
    const before = progressBodyBytes(pairs);
    dropProgressData(dropped);
    const after = progressBodyBytes(dropped);
    const retained = JSON.stringify(dropped);
    for (const needle of heavy) {
      assert.equal(retained.includes(needle), false, `${source}: "${needle}" must not be retained`);
    }
    assert.equal(retained.includes('toolUseResult'), false, `${source}: toolUseResult must not be retained`);
    assert.ok(after < before * 0.3, `${source}: retained progress content must shrink substantially (${before} -> ${after})`);
    for (const pair of dropped) {
      for (const e of pair.progressEntries) {
        const blocks = Array.isArray(e.message.content) ? e.message.content : [];
        assert.deepEqual(blocks.filter(b => b.type !== 'text'), [], `${source}: only text blocks may remain`);
      }
    }
  }
});

