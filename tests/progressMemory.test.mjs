test('P-5b: switching templates changes the analysis fingerprint and clears the cache', async () => {
  const dir = mkTmp('ccx-progress-cache-');
  try {
    const filePath = path.join(dir, 'a.jsonl');
    fs.writeFileSync(filePath, 'x\n', 'utf-8');
    const st = fs.statSync(filePath);
    const file = {
      filePath,
      root: { dir: '/logs', origin: 'standard', stableRootKey: 'std', recursive: false },
      snapshot: { size: st.size, mtimeMs: st.mtimeMs, dev: st.dev, ino: st.ino },
    };
    const cache = createAnalysisCache();
    const key = cacheKey('claude', file);
    cache.beginCycle();
    cache.useFingerprint(JSON.stringify({ template: TEMPLATES.none }));
    await cache.get(key, file);
    await cache.set(key, file, { outcome: 'used', session: { tag: 'slim' } });
    cache.endCycle();

    cache.beginCycle();
    cache.useFingerprint(JSON.stringify({ template: TEMPLATES.none }));
    assert.equal((await cache.get(key, file)).session.tag, 'slim', 'the same template reuses the entry');
    cache.endCycle();

    cache.beginCycle();
    cache.useFingerprint(JSON.stringify({ template: TEMPLATES.both }));
    assert.equal(await cache.get(key, file), undefined,
      'a slim session is not reused after switching to a template that uses Progress');
    cache.endCycle();
  } finally { rmrf(dir); }
});

