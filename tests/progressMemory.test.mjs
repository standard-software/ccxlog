function childEnv(home) {
  return { ...process.env, HOME: home, USERPROFILE: home, HOMEDRIVE: '', HOMEPATH: '', TZ: 'UTC' };
}

function runCliUtc(args, home) {
  const r = spawnSync(process.execPath, [CLI, ...args], { env: childEnv(home), cwd: ROOT, encoding: 'utf-8' });
  return { code: r.status, stdout: r.stdout ?? '', stderr: r.stderr ?? '' };
}

function sha256Text(s) {
  return crypto.createHash('sha256').update(s, 'utf-8').digest('hex');
}

function fixtureWorkspace(t) {
  const home = mkTmp('ccx-progress-');
  const project = path.join(home, 'proj');
  const out = path.join(project, 'CCXLOG');
  writeProgressFixture(home, project);
  if (t) t.after(() => { killLiveWatches(); rmrf(home); });
  return { home, project, out };
}

function clearMd(dir) {
  fs.mkdirSync(dir, { recursive: true });
  for (const f of fs.readdirSync(dir)) {
    if (f.endsWith('.md')) fs.rmSync(path.join(dir, f));
  }
}

function renderCombination(ws, tplKey, modeKey) {
  clearMd(ws.out);
  useTemplate(ws.out, tplKey);
  const r = runCliUtc([ws.project, ...MODES[modeKey]], ws.home);
  assert.equal(r.code, 0, `${tplKey}/${modeKey}: ${r.stderr}`);
  const text = fs.readFileSync(path.join(ws.out, AGGREGATE_NAME[modeKey]), 'utf-8');
  return normalize(text, { home: ws.home, project: ws.project });
}

