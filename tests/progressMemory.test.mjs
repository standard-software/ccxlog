const liveWatches = new Set();

function killLiveWatches() {
  for (const c of liveWatches) c.kill('SIGKILL');
  liveWatches.clear();
}

function startWatchUtc(args, home) {
  const child = spawn(process.execPath, [CLI, ...args], { env: childEnv(home), cwd: ROOT });
  liveWatches.add(child);
  const state = { stdout: '', stderr: '' };
  child.stdout.on('data', d => { state.stdout += d; });
  child.stderr.on('data', d => { state.stderr += d; });
  child.on('exit', () => liveWatches.delete(child));
  return { child, state };
}

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function waitForOutput(ws, fileName, expectedHash, timeoutMs = 40000) {
  const deadline = Date.now() + timeoutMs;
  let last = '(output file does not exist yet)';
  for (;;) {
    try {
      const text = fs.readFileSync(path.join(ws.out, fileName), 'utf-8');
      last = normalize(text, { home: ws.home, project: ws.project });
      if (sha256Text(last) === expectedHash) return last;
    } catch {  }
    if (Date.now() >= deadline) return { timeout: true, last };
    await sleep(150);
  }
}

test('P-6: switching templates during watch always produces correct output', async (t) => {
  const ws = fixtureWorkspace(t);
  clearMd(ws.out);
  useTemplate(ws.out, 'none');
  const w = startWatchUtc([ws.project, '--watch'], ws.home);
  try {
    let r = await waitForOutput(ws, 'ccxlog.md', GOLDEN['none/ccxlog']);
    assert.equal(r.timeout, undefined, `initial output without Progress differs:\n${r.last}\n${w.state.stderr}`);

    useTemplate(ws.out, 'both');
    r = await waitForOutput(ws, 'ccxlog.md', GOLDEN['both/ccxlog']);
    assert.equal(r.timeout, undefined, `output after enabling Progress differs:\n${r.last}\n${w.state.stderr}`);

    useTemplate(ws.out, 'none');
    r = await waitForOutput(ws, 'ccxlog.md', GOLDEN['none/ccxlog']);
    assert.equal(r.timeout, undefined, `output after disabling Progress differs:\n${r.last}\n${w.state.stderr}`);

    useTemplate(ws.out, 'summary');
    r = await waitForOutput(ws, 'ccxlog.md', GOLDEN['summary/ccxlog']);
    assert.equal(r.timeout, undefined, `output after switching to %Progress% alone differs:\n${r.last}\n${w.state.stderr}`);
  } finally {
    w.child.kill('SIGKILL');
  }
});

