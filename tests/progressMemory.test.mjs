test('P-4c: unused top-level ID and timestamp fields are removed', async (t) => {
  const src = await fixturePairs(t);
  for (const [source, pairs] of Object.entries(src)) {
    const beforeKeys = new Set(pairs.flatMap(p => p.progressEntries.flatMap(e => Object.keys(e))));
    for (const key of ['uuid', 'timestamp']) {
      assert.equal(beforeKeys.has(key), true, `${source}: ${key} exists before discarding`);
    }
    const dropped = structuredClone(pairs);
    dropProgressData(dropped);
    for (const pair of dropped) {
      for (const e of pair.progressEntries) {
        for (const key of DEAD_KEYS) {
          assert.equal(key in e, false, `${source}: ${key} must not be retained`);
        }
        assert.equal(typeof e.type, 'string', `${source}: type remains`);
      }
    }
  }
  const cxDropped = structuredClone(src.codex);
  dropProgressData(cxDropped);
  assert.equal(
    cxDropped.some(p => p.progressEntries.some(e => e.isProgressOnly === true)), true,
    'isProgressOnly remains',
  );
});

